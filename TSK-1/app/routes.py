"""
===============================================================================
Файл: routes.py (версия без авторизации)
===============================================================================

Этот файл описывает REST API для объявлений на Flask.

Он реализует 2 набора маршрутов:

1) /ads
   - GET    /ads  -> получить список объявлений
   - POST   /ads  -> создать объявление

2) /ads/<id>
   - GET    /ads/<id>     -> получить объявление по id
   - PATCH  /ads/<id>     -> частично обновить объявление
   - DELETE /ads/<id>     -> удалить объявление

-------------------------------------------------------------------------------
Особенность этой версии:
-------------------------------------------------------------------------------
- В этой версии НЕТ системы пользователей и НЕТ JWT.
- Поэтому поле "owner" (владелец) передаётся клиентом в JSON.
- Любой пользователь может удалять и менять любые объявления.
- Это небезопасно, но подходит для первого (базового) этапа задания.

-------------------------------------------------------------------------------
Как выглядит объявление (пример JSON):
-------------------------------------------------------------------------------
{
  "id": 1,
  "title": "Продам ноутбук",
  "description": "Core i7, 16GB RAM",
  "created_at": "19.01.2026 10:40:11",
  "owner": "Ivan"
}

-------------------------------------------------------------------------------
Типовые ответы:
-------------------------------------------------------------------------------
- 200 OK          -> успешный GET / PATCH / DELETE
- 201 Created     -> успешный POST (создание)
- 400 Bad Request -> неверные данные в запросе
- 404 Not Found   -> объявление не найдено
-------------------------------------------------------------------------------

Ниже построчное объяснение кода.
===============================================================================
"""

# Flask:
# Blueprint  - позволяет "группировать" маршруты в модуль
# request    - содержит данные входящего HTTP-запроса (JSON, headers, args, etc.)
# jsonify    - удобная функция, которая превращает dict/list в JSON Response
from flask import Blueprint, request, jsonify

# db  - объект SQLAlchemy, через него мы обращаемся к базе данных
# Ad  - модель объявления, описывает таблицу "ads"
from .models import db, Ad

# ApiError - собственное исключение проекта.
# Оно используется для единых JSON ошибок:
#   raise ApiError("text", 400)
# обработчик ошибок в errors.py превратит это в JSON ответ.
from .errors import ApiError


# -----------------------------------------------------------------------------
# Blueprint: ads_bp
# -----------------------------------------------------------------------------
# Blueprint создаёт отдельный "контейнер" маршрутов.
# Первый параметр "ads" — имя модуля (внутреннее).
# __name__ — стандартное значение для Flask.
#
# Дальше этот blueprint подключают в app/__init__.py:
#   app.register_blueprint(ads_bp)
#
ads_bp = Blueprint("ads", __name__)


# -----------------------------------------------------------------------------
# validate_ad_payload()
# -----------------------------------------------------------------------------
def validate_ad_payload(data: dict, required_fields: list[str]):
    """
    Универсальная валидация входного JSON.

    Для чего нужна:
    - чтобы не писать одинаковые проверки в каждом POST/PATCH
    - чтобы входные данные всегда были в одном формате

    Параметры:
    - data: dict
        Это JSON-объект, который пришёл в запросе.
        Мы его получаем так:
            data = request.get_json(silent=True)

    - required_fields: list[str]
        Список обязательных ключей.
        Например при создании объявления нужно:
            ["title", "description", "owner"]

    Что проверяем:
    1) data обязательно должен быть dict (JSON object)
       Если клиент отправил:
       - пустое тело
       - неверный JSON
       - JSON-массив []
       - строку
       то data не будет dict

    2) каждое обязательное поле должно быть в data

    3) каждое поле должно быть непустой строкой
       (после strip() строка не должна стать пустой)
    """

    # Проверка №1: JSON должен быть объектом (dict)
    # Иначе нельзя корректно обращаться по ключам data["title"]
    if not isinstance(data, dict):
        # 400 Bad Request — запрос неправильный
        raise ApiError("Body must be JSON object", 400)

    # required_fields — список обязательных полей
    for field in required_fields:

        # Проверка №2: поле должно быть в JSON
        # если ключа нет, значит клиент не передал обязательное поле
        if field not in data:
            raise ApiError(f"Field '{field}' is required", 400)

        # Проверка №3: поле должно быть строкой и не пустым
        # isinstance(..., str) защищает от int/bool/list/etc.
        # strip() убирает пробелы:
        #   "   " -> станет "" (пустая строка)
        if not isinstance(data[field], str) or not data[field].strip():
            raise ApiError(f"Field '{field}' must be a non-empty string", 400)


# -----------------------------------------------------------------------------
# get_ad_or_404()
# -----------------------------------------------------------------------------
def get_ad_or_404(ad_id: int) -> Ad:
    """
    Функция для получения объявления по id.

    Зачем нужна:
    - чтобы не дублировать код поиска объявления
    - чтобы централизованно выдавать 404

    ad_id: int — id объявления из URL: /ads/<int:ad_id>

    Логика:
    - ищем запись по id
    - если не нашли -> 404
    - если нашли -> возвращаем Ad
    """

    # Ad.query.get(ad_id) — поиск по primary key (id)
    # Вернёт:
    # - объект Ad, если найден
    # - None, если нет
    ad = Ad.query.get(ad_id)

    if ad is None:
        # 404 Not Found — ресурс не найден
        raise ApiError("Ad not found", 404)

    return ad


# =============================================================================
# Маршрут 1: /ads
# =============================================================================
#
# Здесь используется один обработчик на два метода:
# - POST /ads
# - GET  /ads
#
# Это удобно, но иногда в "большом" проекте делают раздельно:
#   @ads_bp.get("/ads")
#   @ads_bp.post("/ads")
#
# Здесь сделано через route(..., methods=[...]) для простоты.
#
# =============================================================================
@ads_bp.route("/ads", methods=["POST", "GET"])
def ads_collection():
    """
    Обработчик коллекции объявлений.

    POST /ads:
      создаёт объявление

    GET /ads:
      возвращает список объявлений
    """

    # -------------------------------------------------------------------------
    # POST /ads — создание нового объявления
    # -------------------------------------------------------------------------
    if request.method == "POST":

        # Получаем JSON из тела запроса
        # silent=True:
        # - если JSON неправильный, то вместо исключения получим None
        # - мы сами обработаем это через validate_ad_payload
        data = request.get_json(silent=True)

        # Проверяем обязательные поля:
        # - title
        # - description
        # - owner (в этой версии владелец строкой)
        validate_ad_payload(data, required_fields=["title", "description", "owner"])

        # Создаём объект объявления через модель Ad
        #
        # Здесь мы используем data["title"] (не get),
        # потому что validate_ad_payload уже гарантирует, что ключ есть.
        #
        # strip() убирает пробелы по краям строки
        ad = Ad(
            title=data["title"].strip(),
            description=data["description"].strip(),
            owner=data["owner"].strip(),
        )

        # Добавляем в сессию SQLAlchemy
        db.session.add(ad)

        # Фиксируем изменения в базе данных
        db.session.commit()

        # Возвращаем JSON с созданным объектом и статус 201
        # 201 Created — правильный код для создания ресурса.
        return jsonify(ad.to_dict()), 201

    # -------------------------------------------------------------------------
    # GET /ads — список объявлений
    # -------------------------------------------------------------------------

    # Берём все объявления из БД
    # order_by(Ad.created_at.desc()) — сортировка: новые сверху
    ads = Ad.query.order_by(Ad.created_at.desc()).all()

    # Преобразуем каждый объект в dict
    # jsonify превращает список dict'ов в JSON
    return jsonify([ad.to_dict() for ad in ads]), 200


# =============================================================================
# Маршрут 2: /ads/<id>
# =============================================================================
#
# Один обработчик на 3 метода:
# - GET /ads/<id>
# - DELETE /ads/<id>
# - PATCH /ads/<id>
#
# =============================================================================
@ads_bp.route("/ads/<int:ad_id>", methods=["GET", "DELETE", "PATCH"])
def ad_item(ad_id: int):
    """
    Обработчик одного объявления по id.

    GET:
      получить объявление

    DELETE:
      удалить объявление

    PATCH:
      частично обновить объявление
    """

    # Сначала получаем объявление.
    # Если его нет -> вылетим с 404.
    ad = get_ad_or_404(ad_id)

    # -------------------------------------------------------------------------
    # GET /ads/<id>
    # -------------------------------------------------------------------------
    if request.method == "GET":
        # Возвращаем JSON объявления
        return jsonify(ad.to_dict()), 200

    # -------------------------------------------------------------------------
    # DELETE /ads/<id>
    # -------------------------------------------------------------------------
    if request.method == "DELETE":
        # Удаляем объект из базы
        db.session.delete(ad)
        db.session.commit()

        # Возвращаем подтверждение удаления
        return jsonify({"status": "deleted", "id": ad_id}), 200

    # -------------------------------------------------------------------------
    # PATCH /ads/<id>
    # -------------------------------------------------------------------------
    #
    # PATCH — это частичное обновление:
    # можно отправить только одно поле (например title)
    # и обновить только его.
    #
    # Пример запроса:
    # PATCH /ads/1
    # {
    #   "title": "Новый заголовок"
    # }
    #
    # -------------------------------------------------------------------------

    data = request.get_json(silent=True)

    # JSON должен быть объектом
    if not isinstance(data, dict):
        raise ApiError("Body must be JSON object", 400)

    # Разрешённые поля, которые можно менять
    # owner тут разрешён, но это небезопасно (в версии с JWT это запрещаем)
    allowed_fields = {"title", "description", "owner"}

    # Проверяем, что клиент не прислал лишних полей
    # Например, если он отправит:
    # { "created_at": "..."}
    # -> это должно быть запрещено
    unknown_fields = set(data.keys()) - allowed_fields
    if unknown_fields:
        raise ApiError(f"Unknown fields: {sorted(list(unknown_fields))}", 400)

    # Если пришёл title — валидируем и обновляем
    if "title" in data:
        if not isinstance(data["title"], str) or not data["title"].strip():
            raise ApiError("Field 'title' must be a non-empty string", 400)
        ad.title = data["title"].strip()

    # Если пришёл description — валидируем и обновляем
    if "description" in data:
        if not isinstance(data["description"], str) or not data["description"].strip():
            raise ApiError("Field 'description' must be a non-empty string", 400)
        ad.description = data["description"].strip()

    # Если пришёл owner — валидируем и обновляем
    # Это слабое место первой версии: любой может сменить владельца.
    if "owner" in data:
        if not isinstance(data["owner"], str) or not data["owner"].strip():
            raise ApiError("Field 'owner' must be a non-empty string", 400)
        ad.owner = data["owner"].strip()

    # Сохраняем изменения
    db.session.commit()

    # Возвращаем обновлённое объявление
    return jsonify(ad.to_dict()), 200


